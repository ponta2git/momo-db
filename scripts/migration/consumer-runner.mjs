import { randomUUID } from 'node:crypto';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { assertOwned } from './local.mjs';
import { command } from './process.mjs';
import { digest, requireCondition as check } from './files.mjs';

export function consumerEnvironment(manifest, proof, config, machineId) {
  check(proof?.runId === manifest.runId && proof.applicationDataUnchanged === true &&
    proof.access?.superuser === false && proof.access?.direct_login === true &&
    /^momo_rehearsal_app_[a-f0-9]{12}$/.test(proof.localRole) &&
    ['momo_rehearsal_smoke', 'momo_rehearsal_recovery'].includes(proof.database),
  'VALIDATED_LOCAL_ROLE_REQUIRED');
  check(['api', 'worker', 'summit'].includes(config.consumer) &&
    /^sha256:[a-f0-9]{64}$/.test(config.image) && Array.isArray(config.ledger), 'FIXED_CONSUMER_REQUIRED');
  check(/^[a-f0-9]{64}$/.test(manifest.local?.container), 'OWNED_CONTAINER_REQUIRED');
  const env = { ...config.env,
    DATABASE_URL: `postgresql://${proof.localRole}@${manifest.local.container.slice(0, 12)}:5432/${proof.database}?sslmode=disable`,
    MOMO_CUTOVER_MODE: 'maintenance',
    MOMO_CUTOVER_EXPECTED_DATABASE: proof.database,
    MOMO_CUTOVER_EXPECTED_ROLE: proof.localRole,
    MOMO_CUTOVER_EXPECTED_LEDGER_SHA256: digest(config.ledger),
    MOMO_CUTOVER_IMAGE_DIGEST: config.image,
    MOMO_CUTOVER_REPORT_PATH: '/tmp/momo-cutover-report.json',
    FLY_MACHINE_ID: machineId,
  };
  for (const [name, value] of Object.entries(env)) {
    check(/^[A-Z][A-Z0-9_]*$/.test(name) && typeof value === 'string' && !/[\r\n\0]/.test(value),
      'CONSUMER_ENV_INVALID');
  }
  return env;
}

/** Keeps the exact image attached to the owned, egress-isolated database for the callback. */
export async function withMaintenanceConsumer(manifest, proof, config, operation) {
  await assertOwned(manifest);
  const name = `momo-probe-${randomUUID()}`;
  const env = consumerEnvironment(manifest, proof, config, name);
  const directory = await mkdtemp(join(tmpdir(), 'momo-consumer-'));
  const envFile = join(directory, 'environment');
  const startedAt = Date.now();
  let created = false;
  try {
    await writeFile(envFile, Object.entries(env).map(([key, value]) => `${key}=${value}`).join('\n'),
      { mode: 0o600, flag: 'wx' });
    const id = await command('docker', ['create', '--name', name,
      '--label', `io.momo.migration.run=${manifest.runId}`, '--network', manifest.local.network,
      '--read-only', '--tmpfs', '/tmp:rw,nosuid,nodev,size=128m',
      '--cap-drop', 'ALL', ...(config.consumer === 'worker' ? ['--cap-add', 'SETUID', '--cap-add', 'SETGID'] : []),
      '--security-opt', 'no-new-privileges',
      '--memory', '1g', '--memory-swap', '1g', '--cpus', '1', '--pids-limit', '256',
      '--env-file', envFile, config.image]);
    created = true;
    check(/^[a-f0-9]{64}$/.test(id), 'CONSUMER_CONTAINER_ID_INVALID');
    await command('docker', ['start', id]);
    const deadline = Date.now() + 90000;
    let report;
    while (Date.now() < deadline) {
      const item = JSON.parse(await command('docker', ['inspect', id]))[0];
      check(item?.Image === config.image && item.State?.Running &&
        Object.keys(item.NetworkSettings.Networks).length === 1 &&
        Object.values(item.NetworkSettings.Networks)[0].NetworkID === manifest.local.network &&
        !Object.keys(item.HostConfig.PortBindings ?? {}).length, 'CONSUMER_NOT_ISOLATED_OR_EXITED');
      try {
        const reportUser = config.consumer === 'summit' ? '1000:1000' : '10001:10001';
        report = JSON.parse(await command('docker', ['exec', '--user', reportUser, id, 'cat', env.MOMO_CUTOVER_REPORT_PATH]));
      } catch { await delay(250); continue; }
      break;
    }
    check(report?.consumer === config.consumer && report.readOnly === true && report.mode === 'maintenance' &&
      report.database === proof.database && report.role === proof.localRole &&
      Array.isArray(report.ledger) &&
      digest(report.ledger.map(row => ({ hash: row.hash, created_at: row.created_at }))) === digest(config.ledger) &&
      report.machine?.id === name &&
      report.machine.imageDigest === config.image && typeof report.machine.bootId === 'string' &&
      Date.parse(report.observedAt) >= startedAt && Date.parse(report.observedAt) <= Date.now(),
    'CONSUMER_PROCESS_REPORT_INVALID');
    return await operation({ id, report });
  } finally {
    // Name is generated by this invocation; never clean up by broad labels.
    try {
      if (created) {
        await command('docker', ['stop', '--time', '10', name]);
        await command('docker', ['rm', name]);
      }
    } finally { await rm(directory, { recursive: true, force: true }); }
  }
}
